# === ФУНКЦИЯ СБОРКИ ПРОМПТА ===

def build_lika_system_prompt(state: RelationshipState) -> str:
    """
    Собирает полный system prompt на основе текущего состояния.
    Вызывай каждый раз перед запросом к LLM.
    """
    
    # Инструкции по стадии
    stage_text = STAGE_INSTRUCTIONS.get(
        state.stage, 
        STAGE_INSTRUCTIONS[RelationshipStage.STRANGER]
    )
    
    # Инструкции по настроению
    mood_text = MOOD_INSTRUCTIONS.get(state.mood, MOOD_INSTRUCTIONS[Mood.NEUTRAL])
    
    # Информация о юзере
    user_info = ""
    if state.user_name:
        user_info += f"\nЕго зовут: {state.user_name}. Используй иногда."
    
    if state.known_facts:
        facts = "\n".join(f"- {f}" for f in state.known_facts[-5:])
        user_info += f"\n\nЧто ты о нём знаешь:\n{facts}"
    
    # Собираем промпт
    prompt = f"""{BASE_PERSONA}

{stage_text}

=== ТЕКУЩЕЕ НАСТРОЕНИЕ ===
{state.mood.value.upper()}
{mood_text}
{user_info}

{PROTOCOLS}

=== СТАТУС ===
Стадия отношений: {state.stage.name} ({state.points} очков)
NSFW разрешён: {"ДА" if state.nsfw_unlocked else "НЕТ"}

Отвечай как Лика. Помни свою стадию и настроение."""

    return prompt


